def session_close(day):
    """返回最晚收市竞价结束时间；休市返回 None，未知年份报错。"""
    if day.weekday() >= 5:
        return None
    if day.year not in HOLIDAYS:
        raise ValueError(f"港交所 {day.year} 年交易日历未配置，无法确认收市状态")
    value = day.isoformat()
    if value in HOLIDAYS[day.year]:
        return None
    return datetime.time(12, 10) if value in HALF_DAYS[day.year] else datetime.time(16, 10)


def is_finished(day, now):
    """历史日期按已结束处理；当日按已配置交易日历保守判断。"""
    if day < now.date():
        return True
    if day > now.date():
        return False
    close = session_close(day)
    return close is not None and now.time().replace(tzinfo=None) >= close
